/* =========================================================
   STEP 1. Create the logging table
   This table stores:
   - when the log was created
   - from which module/procedure
   - the logical line/step number
   - the message itself
   - the Oracle session id

   This directly covers the assignment requirement for a
   logging table named DEBUG_LOG.
   ========================================================= */

CREATE TABLE debug_log (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_time TIMESTAMP DEFAULT SYSTIMESTAMP,
    module_name VARCHAR2(100),
    line_no NUMBER,
    log_message VARCHAR2(4000),
    session_id VARCHAR2(50) DEFAULT SYS_CONTEXT('USERENV', 'SESSIONID')
);

