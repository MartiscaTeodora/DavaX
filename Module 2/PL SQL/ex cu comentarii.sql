/* =========================================================
   STEP 8. Create the main procedure
   Business rule from assignment:
   - if commission_pct is NOT NULL:
       increase salary proportionally by that percentage
   - if commission_pct IS NULL:
       increase salary by 2%

   The procedure also logs important steps:
   - start
   - employee read
   - salary/commission values
   - chosen calculation branch
   - new salary
   - update completed
   - procedure end
   ========================================================= */

CREATE OR REPLACE PROCEDURE adjust_salaries_by_commission IS

    /* Explicit cursor requested/allowed by the assignment */
    CURSOR emp_cursor IS
        SELECT employee_id, salary, commission_pct
        FROM employees;

    /* Anchored type: follows the data type of employees.salary */
    v_new_salary employees.salary%TYPE;

BEGIN
    /* Enable debug logging for this run */
    debug_utils.enable_debug;

    debug_utils.log_msg(
        'adjust_salaries_by_commission',
        1,
        'Procedure started'
    );

    FOR rec IN emp_cursor LOOP

        /* Log which employee is being processed */
        debug_utils.log_msg(
            'adjust_salaries_by_commission',
            2,
            'Processing employee_id = ' || rec.employee_id
        );

        /* Log current input values */
        debug_utils.log_variable(
            'adjust_salaries_by_commission',
            3,
            'Current salary',
            TO_CHAR(rec.salary)
        );

        debug_utils.log_variable(
            'adjust_salaries_by_commission',
            4,
            'Commission pct',
            NVL(TO_CHAR(rec.commission_pct), 'NULL')
        );

        /* Apply assignment rule */
        IF rec.commission_pct IS NOT NULL THEN
            v_new_salary := rec.salary + (rec.salary * rec.commission_pct);

            debug_utils.log_msg(
                'adjust_salaries_by_commission',
                5,
                'Commission-based increase applied'
            );
        ELSE
            v_new_salary := rec.salary * 1.02;

            debug_utils.log_msg(
                'adjust_salaries_by_commission',
                6,
                'Default 2% increase applied'
            );
        END IF;

        /* Log the computed result */
        debug_utils.log_variable(
            'adjust_salaries_by_commission',
            7,
            'New salary',
            TO_CHAR(v_new_salary)
        );

        /* Update the employee record */
        UPDATE employees
        SET salary = v_new_salary
        WHERE employee_id = rec.employee_id;

        debug_utils.log_msg(
            'adjust_salaries_by_commission',
            8,
            'Salary updated for employee_id = ' || rec.employee_id
        );

    END LOOP;

    COMMIT;

    debug_utils.log_msg(
        'adjust_salaries_by_commission',
        9,
        'Procedure completed successfully'
    );

    debug_utils.disable_debug;

EXCEPTION
    WHEN OTHERS THEN
        /* Log the exception in a reusable, uniform way */
        debug_utils.log_error('adjust_salaries_by_commission', SQLERRM);
        ROLLBACK;
        RAISE;
END adjust_salaries_by_commission;
