/* =========================================================
   STEP 4. Create package specification
   This package centralizes all debugging operations.

   g_debug_mode:
   - TRUE  = logging enabled
   - FALSE = logging disabled

   The package exposes reusable procedures for:
   - enabling debug mode
   - disabling debug mode
   - logging messages
   - logging variable values
   - logging errors
   ========================================================= */

CREATE OR REPLACE PACKAGE debug_utils AS

    /* Global flag controlling whether normal logs are written */
    g_debug_mode BOOLEAN := FALSE;

    /* Turn debug logging on */
    PROCEDURE enable_debug;

    /* Turn debug logging off */
    PROCEDURE disable_debug;

    /* Log a generic execution message */
    PROCEDURE log_msg(
        p_module_name VARCHAR2,
        p_line_no     NUMBER,
        p_message     VARCHAR2
    );

    /* Log a variable name/value pair */
    PROCEDURE log_variable(
        p_module_name VARCHAR2,
        p_line_no     NUMBER,
        p_name        VARCHAR2,
        p_value       VARCHAR2
    );

    /* Log an error message */
    PROCEDURE log_error(
        p_proc VARCHAR2,
        p_err  VARCHAR2
    );

END debug_utils;
/

/* =========================================================
   STEP 5. Create package body
   This contains the actual implementation.

   Important adaptation:
   - log_error uses PRAGMA AUTONOMOUS_TRANSACTION
   so that error logs are preserved even if the main
   transaction is rolled back.

   This is a useful improvement for real debugging.
   ========================================================= */

CREATE OR REPLACE PACKAGE BODY debug_utils AS

    PROCEDURE enable_debug IS
    BEGIN
        g_debug_mode := TRUE;
    END enable_debug;

    PROCEDURE disable_debug IS
    BEGIN
        g_debug_mode := FALSE;
    END disable_debug;

    PROCEDURE log_msg(
        p_module_name VARCHAR2,
        p_line_no     NUMBER,
        p_message     VARCHAR2
    ) IS
    BEGIN
        IF g_debug_mode THEN
            INSERT INTO debug_log (module_name, line_no, log_message)
            VALUES (p_module_name, p_line_no, p_message);
        END IF;
    END log_msg;

    PROCEDURE log_variable(
        p_module_name VARCHAR2,
        p_line_no     NUMBER,
        p_name        VARCHAR2,
        p_value       VARCHAR2
    ) IS
    BEGIN
        IF g_debug_mode THEN
            INSERT INTO debug_log (module_name, line_no, log_message)
            VALUES (p_module_name, p_line_no, p_name || ' = ' || p_value);
        END IF;
    END log_variable;

    PROCEDURE log_error(
        p_proc VARCHAR2,
        p_err  VARCHAR2
    ) IS
        PRAGMA AUTONOMOUS_TRANSACTION;
    BEGIN
        /* Error logs are always stored, even if debug mode is off */
        INSERT INTO debug_log (module_name, line_no, log_message)
        VALUES (
            p_proc,
            NULL,
            'ERROR: ' || p_err || ' | BACKTRACE: ' || DBMS_UTILITY.FORMAT_ERROR_BACKTRACE
        );

        COMMIT;
    END log_error;

END debug_utils;
/

